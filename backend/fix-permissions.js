const { PrismaClient } = require('@prisma/client');
const prisma = new PrismaClient();

async function main() {
  const result = await prisma.user.updateMany({
    where: { systemRole: 'CEO' },
    data: { canManageUsers: true }
  });
  console.log(`Updated ${result.count} existing CEOs to canManageUsers = true.`);
}

main()
  .catch(e => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
